#!/usr/bin/env python3
"""
Makes one cloud speech-bubble image per guide step (text baked in, wrapped over several lines)
and writes the ItemsAdder font_images config for them.

Run from the project folder after you edit the steps in src/main/resources/config.yml:
    pip install pillow pyyaml
    python tools/generate_bubbles.py
Then copy itemsadder-pack/contents/guide to plugins/ItemsAdder/contents/ and run /iazip.
"""
import re, sys, os
from PIL import Image, ImageDraw, ImageFont
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONFIG = os.path.join(ROOT, "src/main/resources/config.yml")       # or point to plugins/ServerGuide/config.yml
PACK = os.path.join(ROOT, "itemsadder-pack/contents/guide")
FONT_DIR = os.path.join(PACK, "resourcepack/guide/textures/font")

# Put a .ttf here for a different look (e.g. a Minecraft-style font you have the licence for)
FONT_CANDIDATES = [
    os.path.join(ROOT, "tools/font.ttf"),
    "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
    "C:/Windows/Fonts/arialbd.ttf",
    "/System/Library/Fonts/Supplemental/Arial Bold.ttf",
]
PLAYER_WORD = "friend"      # baked images cannot contain the real player name

S = 4                        # image pixels per GUI pixel
CW, CH = 150 * S, 147 * S    # canvas: 150 x 147 GUI px (bottom edge sits on the action-bar baseline)
BODY = (6 * S, 6 * S, 144 * S, 96 * S)   # cloud body
TEXT = (22 * S, 18 * S, 128 * S, 84 * S) # text area inside the cloud

def load_font(size):
    for p in FONT_CANDIDATES:
        if os.path.exists(p):
            return ImageFont.truetype(p, size)
    return ImageFont.load_default()

def clean(t):
    t = str(t).replace("<player>", PLAYER_WORD)
    t = re.sub(r"<[^>]+>", "", t)
    return t.strip()

def wrap(draw, text, font, width):
    lines, cur = [], ""
    for w in text.split():
        t = (cur + " " + w).strip()
        if draw.textlength(t, font=font) <= width:
            cur = t
        else:
            lines.append(cur); cur = w
    if cur: lines.append(cur)
    return lines

def cloud(draw, box, fill, dx=0, dy=0):
    import math
    x0, y0, x1, y1 = box
    cx, cy = (x0 + x1) / 2 + dx, (y0 + y1) / 2 + dy
    rx, ry = (x1 - x0) / 2, (y1 - y0) / 2
    r = 17 * S
    draw.ellipse([cx - rx * .86, cy - ry * .86, cx + rx * .86, cy + ry * .86], fill=fill)
    n = 14
    for i in range(n):                       # bumps around the edge
        a = 2 * math.pi * i / n
        bx, by = cx + (rx - r) * math.cos(a), cy + (ry - r) * math.sin(a)
        draw.ellipse([bx - r, by - r, bx + r, by + r], fill=fill)
    # tail (bottom-left, points at the character)
    tail = [(x0 + 26 * S + dx, y1 - 26 * S + dy), (x0 + 64 * S + dx, y1 - 24 * S + dy), (x0 + 6 * S + dx, y1 + 28 * S + dy)]
    draw.polygon(tail, fill=fill)

def make(text, path):
    im = Image.new("RGBA", (CW, CH), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    o = 2 * S                                            # outline thickness
    for dx in (-o, 0, o):
        for dy in (-o, 0, o):
            cloud(d, BODY, (70, 55, 40, 255), dx, dy)        # outline
    cloud(d, BODY, (255, 255, 255, 255))                 # fill
    tx0, ty0, tx1, ty1 = TEXT
    size = 11 * S
    while size > 5 * S:
        f = load_font(size)
        lines = wrap(d, text, f, tx1 - tx0)
        lh = int(size * 1.25)
        if len(lines) * lh <= ty1 - ty0:
            break
        size -= S // 2
    total = len(lines) * lh
    y = ty0 + (ty1 - ty0 - total) / 2
    for line in lines:
        w = d.textlength(line, font=f)
        d.text((tx0 + (tx1 - tx0 - w) / 2, y), line, font=f, fill=(60, 45, 30, 255))
        y += lh
    im.save(path)

def main():
    cfg = yaml.safe_load(open(CONFIG, encoding="utf-8"))
    steps = cfg.get("steps", [])
    os.makedirs(FONT_DIR, exist_ok=True)
    for f in os.listdir(FONT_DIR):
        if re.fullmatch(r"bubble_\d+\.png", f):
            os.remove(os.path.join(FONT_DIR, f))
    out = ["info:", "  namespace: guide", "",
           "# Generated by tools/generate_bubbles.py - re-run it after editing the steps.",
           "# scale_ratio = height in GUI px, y_position = ascent (must be <= scale_ratio).",
           "font_images:",
           "  guide_girl:", '    path: "font/guide_girl.png"', "    scale_ratio: 110", "    y_position: 49"]
    for i, st in enumerate(steps, 1):
        text = " ".join(clean(x) for x in (st.get("text") or []))
        make(text, os.path.join(FONT_DIR, f"bubble_{i}.png"))
        out += [f"  bubble_{i}:", f'    path: "font/bubble_{i}.png"', "    scale_ratio: 147", "    y_position: 147"]
    open(os.path.join(PACK, "configs/guide_hud.yml"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"Made {len(steps)} bubble images.")

if __name__ == "__main__":
    main()
